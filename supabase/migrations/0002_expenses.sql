-- المصروفات الشهرية (إيجار، رواتب، مصروفات أخرى)
-- شغّل هذا الملف بعد 0001_init.sql في Supabase → SQL Editor

create table if not exists public.expenses (
  id bigint generated by default as identity primary key,
  month date not null check (extract(day from month) = 1),   -- الشهر اللي يخصه المصروف
  category text not null check (category in ('rent', 'salaries', 'other')),
  amount numeric(10, 3) not null check (amount > 0),
  spent_on date not null,                                    -- تاريخ الصرف الفعلي
  description text,
  created_by uuid references public.admins (id) on delete set null,
  updated_by uuid references public.admins (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists expenses_month_idx on public.expenses (month, category);

alter table public.expenses enable row level security;
drop policy if exists expenses_all on public.expenses;
create policy expenses_all on public.expenses for all to authenticated
  using (public.is_admin()) with check (public.is_admin());
