-- ============ المسؤولين ============
create table if not exists public.admins (
  id uuid primary key references auth.users (id) on delete cascade,
  name text not null,
  email text not null unique,
  must_change_password boolean not null default true,
  last_login_at timestamptz,
  created_at timestamptz not null default now()
);

-- هل المستخدم الحالي مسؤول؟ (security definer عشان ما يلف على RLS)
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.admins where id = auth.uid());
$$;

-- ============ الإعدادات (صف واحد) ============
create table if not exists public.settings (
  id int primary key default 1 check (id = 1),
  cutoff_day int not null default 15 check (cutoff_day between 1 and 28),
  default_fee numeric(10, 3) not null default 35 check (default_fee >= 0),
  updated_at timestamptz not null default now()
);
insert into public.settings (id) values (1) on conflict (id) do nothing;

-- ============ العملاء (ثابتين وغير ثابتين) ============
create table if not exists public.customers (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  phone text,
  kind text not null default 'once' check (kind in ('regular', 'once')),
  shift text not null default 'am' check (shift in ('am', 'pm')),
  monthly_fee numeric(10, 3) check (monthly_fee is null or monthly_fee >= 0),
  joined_on date,
  active boolean not null default true,
  notes text,
  created_at timestamptz not null default now()
);
create index if not exists customers_phone_idx on public.customers (phone);
create index if not exists customers_kind_idx on public.customers (kind, active);

-- ============ الفواتير ============
create table if not exists public.invoices (
  id bigint generated by default as identity (start with 1001) primary key,
  customer_id uuid not null references public.customers (id) on delete restrict,
  kind text not null check (kind in ('regular', 'once')),          -- نوع العميل وقت الفاتورة
  shift text not null check (shift in ('am', 'pm')),
  invoice_date date not null,
  period_month date check (period_month is null or extract(day from period_month) = 1), -- «عن شهر» (أول يوم في الشهر). فاضي = دفعة واحدة
  amount numeric(10, 3) not null check (amount > 0),
  status text not null default 'unpaid' check (status in ('paid', 'unpaid')),
  method text check (method in ('cash', 'link', 'wamd', 'other')),
  method_note text,
  paid_on date,
  reference text,
  notes text,
  created_by uuid references public.admins (id) on delete set null,
  updated_by uuid references public.admins (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint paid_needs_method check (status = 'unpaid' or method is not null)
);
create index if not exists invoices_customer_period_idx on public.invoices (customer_id, period_month);
create index if not exists invoices_date_idx on public.invoices (invoice_date desc);
create index if not exists invoices_period_idx on public.invoices (period_month);

-- ============ سجل التعديلات ============
create table if not exists public.invoice_events (
  id bigint generated always as identity primary key,
  invoice_id bigint not null references public.invoices (id) on delete cascade,
  admin_id uuid references public.admins (id) on delete set null,
  action text not null,   -- created | updated | marked_paid | marked_unpaid | printed
  summary text,
  created_at timestamptz not null default now()
);
create index if not exists invoice_events_invoice_idx on public.invoice_events (invoice_id, created_at);

-- ============ الحماية (RLS): المسؤولين فقط ============
alter table public.admins enable row level security;
alter table public.settings enable row level security;
alter table public.customers enable row level security;
alter table public.invoices enable row level security;
alter table public.invoice_events enable row level security;

-- المسؤولين: يشوفون بعض، وكل واحد يعدّل صفه بس
drop policy if exists admins_select on public.admins;
create policy admins_select on public.admins for select to authenticated using (public.is_admin());
drop policy if exists admins_update_self on public.admins;
create policy admins_update_self on public.admins for update to authenticated
  using (id = auth.uid()) with check (id = auth.uid());

drop policy if exists settings_all on public.settings;
create policy settings_all on public.settings for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

drop policy if exists customers_all on public.customers;
create policy customers_all on public.customers for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

drop policy if exists invoices_all on public.invoices;
create policy invoices_all on public.invoices for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

drop policy if exists events_select on public.invoice_events;
create policy events_select on public.invoice_events for select to authenticated using (public.is_admin());
drop policy if exists events_insert on public.invoice_events;
create policy events_insert on public.invoice_events for insert to authenticated
  with check (public.is_admin() and admin_id = auth.uid());
-- سجل التعديلات ما ينمسح ولا يتعدل

-- المسؤول ما يقدر يغيّر بريده أو حالة "كلمة مرور مؤقتة" لغيره: الأعمدة محمية
revoke update on public.admins from authenticated;
grant update (name, must_change_password, last_login_at) on public.admins to authenticated;

-- ===== supabase/migrations/0002_expenses.sql =====
-- المصروفات الشهرية (إيجار، رواتب، مصروفات أخرى)
-- شغّل هذا الملف بعد 0001_init.sql في Supabase → SQL Editor

create table if not exists public.expenses (
  id bigint generated by default as identity primary key,
  month date not null check (extract(day from month) = 1),   -- الشهر اللي يخصه المصروف
  category text not null check (category in ('rent', 'salaries', 'other')),
  amount numeric(10, 3) not null check (amount > 0),
  spent_on date not null,                                    -- تاريخ الصرف الفعلي
  description text,
  created_by uuid references public.admins (id) on delete set null,
  updated_by uuid references public.admins (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists expenses_month_idx on public.expenses (month, category);

alter table public.expenses enable row level security;
drop policy if exists expenses_all on public.expenses;
create policy expenses_all on public.expenses for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

-- ===== supabase/migrations/0003_keep_alive.sql =====
-- نبضة يومية تمنع Supabase المجاني من إيقاف المشروع بسبب قلة الاستخدام
-- ما ترجع أي بيانات، بس تعمل استعلام بسيط على قاعدة البيانات
create or replace function public.keep_alive()
returns int
language sql
stable
security definer
set search_path = public
as $$
  select count(*)::int from public.settings;
$$;
revoke all on function public.keep_alive() from public;
grant execute on function public.keep_alive() to anon, authenticated;

